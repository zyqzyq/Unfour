use super::*;

/// Run against a disposable PostgreSQL instance on the specified loopback port.
/// The table and its owned sequences use UUID-scoped names.
#[tokio::test]
#[ignore = "requires a disposable PostgreSQL instance (UNFOUR_TEST_PG_PORT)"]
async fn export_restore_preserves_owned_sequence_state_and_projection() {
    let port: u16 = std::env::var("UNFOUR_TEST_PG_PORT")
        .expect("test port")
        .parse()
        .unwrap();
    let pool = PgPoolOptions::new()
        .connect_with(
            PgConnectOptions::new()
                .host("127.0.0.1")
                .port(port)
                .username("postgres")
                .database("postgres")
                .options([("search_path", "pg_catalog")]),
        )
        .await
        .unwrap();
    let (service, workspace) = service_with_workspace().await;
    let mut input = postgres_input(&workspace);
    input.port = Some(port);
    input.username = Some("postgres".into());
    input.database = Some("postgres".into());
    let connection = service.save_connection(input).await.unwrap();
    // public is visible during export and deliberately absent during restore.
    let schema = "public";
    let fixture = format!("export_{}", uuid::Uuid::new_v4().simple());
    let table = format!("{fixture}'\"Report");
    let qualified = quote_qualified_identifier(schema, &table);
    let odd_column = "serial'\"id";
    let serial = quote_identifier(odd_column);
    let export_path = std::env::temp_dir().join(format!("{fixture}.sql"));
    let path = export_path.to_str().unwrap();
    let base = DatabaseExportTableInput {
        workspace_id: workspace,
        connection_id: connection.id,
        catalog: None,
        schema: Some(schema.into()),
        table_name: table,
        content: DatabaseExportContent::StructureAndData,
        format: DatabaseExportFormat::Sql,
        destination_path: path.into(),
        columns: None,
        filters: vec![],
        limit: None,
    };

    let payload_seq = quote_qualified_identifier(schema, &format!("{fixture}_payload"));
    let identity_seq = quote_qualified_identifier(schema, &format!("{fixture}_narrow"));
    let initialize = format!(
        "CREATE SEQUENCE {payload_seq} AS bigint START 37 INCREMENT BY 2;
        CREATE TABLE {qualified} (
            {serial} serial PRIMARY KEY,
            down_id bigint GENERATED ALWAYS AS IDENTITY (START WITH -5 INCREMENT BY -4 MINVALUE -997 MAXVALUE -1),
            unused bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 19 INCREMENT BY 3),
            payload_id integer DEFAULT coalesce(nextval('{payload_seq}'::regclass), 0),
            narrow_id bigint GENERATED ALWAYS AS IDENTITY (SEQUENCE NAME {identity_seq}),
            label text
        );
        ALTER SEQUENCE {payload_seq} OWNED BY {qualified}.payload_id;
        ALTER SEQUENCE {identity_seq} AS smallint START -33 INCREMENT -4 MINVALUE -32000 MAXVALUE -10 RESTART -33;
        INSERT INTO {qualified}(label,unused) VALUES ('one', 100),('two',101);"
    );
    sqlx::raw_sql(&initialize).execute(&pool).await.unwrap();
    sqlx::query("SELECT pg_catalog.setval(pg_catalog.pg_get_serial_sequence($1,$2), 70, true)")
        .bind(&qualified)
        .bind(odd_column)
        .execute(&pool)
        .await
        .unwrap();

    // The filtered dump must preserve the source's sequence state, including
    // gaps, descending steps and a never-called sequence with explicit row IDs.
    let mut filtered = base.clone();
    filtered.filters = vec![DatabaseExportFilter {
        column: "label".into(),
        op: unfour_core::models::DatabaseExportFilterOp::Eq,
        values: vec![Some("one".into())],
    }];
    let export = |input| async {
        service.export_table(input).await.unwrap();
        std::fs::read_to_string(path).unwrap()
    };
    let sql = export(filtered).await;
    sqlx::raw_sql(&format!("DROP TABLE {qualified}; {sql}"))
        .execute(&pool)
        .await
        .unwrap();
    let generated =
        format!("INSERT INTO {qualified}(label) VALUES ('new') RETURNING {serial},down_id,unused");
    let next: (i32, i64, i64) = sqlx::query_as(&generated).fetch_one(&pool).await.unwrap();
    assert_eq!(next, (71, -13, 19));
    let cross_type: (i32, i64) = sqlx::query_as(&format!(
        "SELECT payload_id, narrow_id FROM {qualified} WHERE label='new'"
    ))
    .fetch_one(&pool)
    .await
    .unwrap();
    assert_eq!(cross_type, (41, -41));
    let column_forms: (bool, bool) = sqlx::query_as(
        "SELECT bool_or(attname = 'payload_id' AND NOT attnotnull AND attidentity = ''),
                bool_or(attname = 'narrow_id' AND attidentity = 'a')
           FROM pg_attribute WHERE attrelid = $1::regclass",
    )
    .bind(&qualified)
    .fetch_one(&pool)
    .await
    .unwrap();
    assert_eq!(column_forms, (true, true));
    for (column, expected_type) in [("payload_id", "bigint"), ("narrow_id", "smallint")] {
        let actual_type: String = sqlx::query_scalar(
            "SELECT format_type(seqtypid, NULL) FROM pg_sequence
              WHERE seqrelid = pg_get_serial_sequence($1, $2)::regclass",
        )
        .bind(&qualified)
        .bind(column)
        .fetch_one(&pool)
        .await
        .unwrap();
        assert_eq!(actual_type, expected_type);
    }

    // An empty table can still have an advanced sequence (e.g. after DELETE).
    pool.execute(format!("DELETE FROM {qualified}").as_str())
        .await
        .unwrap();
    let sql = export(base.clone()).await;
    sqlx::raw_sql(&format!("DROP TABLE {qualified}; {sql}"))
        .execute(&pool)
        .await
        .unwrap();
    let next: (i32, i64, i64) = sqlx::query_as(&generated).fetch_one(&pool).await.unwrap();
    assert_eq!(next, (72, -17, 22));

    // When the IDs are omitted, replay allocates them naturally; do not reset
    // the target afterwards. A data-only export never changes target sequences.
    let mut projected = base.clone();
    projected.columns = Some(vec!["label".into()]);
    let sql = export(projected).await;
    assert!(!sql.contains("setval("));
    sqlx::raw_sql(&format!("DROP TABLE {qualified}; {sql}"))
        .execute(&pool)
        .await
        .unwrap();
    let next: (i32, i64, i64) = sqlx::query_as(&generated).fetch_one(&pool).await.unwrap();
    assert_eq!(next, (2, -9, 22));

    let sql = export(DatabaseExportTableInput {
        content: DatabaseExportContent::Data,
        ..base.clone()
    })
    .await;
    assert!(!sql.contains("setval("));
    let sql = export(DatabaseExportTableInput {
        content: DatabaseExportContent::Structure,
        ..base
    })
    .await;
    sqlx::raw_sql(&format!("DROP TABLE {qualified}; {sql}"))
        .execute(&pool)
        .await
        .unwrap();
    let first: (Option<i32>, i64) = sqlx::query_as(&format!(
        "INSERT INTO {qualified}(payload_id) VALUES (NULL) RETURNING payload_id,narrow_id"
    ))
    .fetch_one(&pool)
    .await
    .unwrap();
    assert_eq!(first, (None, -33));
    pool.execute(format!("DROP TABLE {qualified}").as_str())
        .await
        .unwrap();
    std::fs::remove_file(export_path).unwrap();
}
