import type { OnMount } from "@monaco-editor/react";

export function configureEditorThemes(
  monaco: { editor: Pick<Parameters<OnMount>[1]["editor"], "defineTheme" | "setTheme"> },
  theme: "dark" | "light",
) {
  // Monaco needs concrete colors. Keep both named themes aligned with styles/*.css
  // so already-mounted API and SQL editors can switch without remounting.
  monaco.editor.defineTheme("unfour-dark", {
    base: "vs-dark",
    inherit: true,
    rules: [
      { token: "keyword", foreground: "cfb7ec" },
      { token: "keyword.sql", foreground: "cfb7ec" },
      { token: "keyword.json", foreground: "cfb7ec" },
      { token: "attribute.name", foreground: "cfb7ec" },
      { token: "string", foreground: "a3dab4" },
      { token: "string.sql", foreground: "a3dab4" },
      { token: "string.value.json", foreground: "a3dab4" },
      { token: "attribute.value", foreground: "a3dab4" },
      { token: "number", foreground: "ecd08d" },
      { token: "number.json", foreground: "ecd08d" },
      { token: "type", foreground: "ecd08d" },
      { token: "string.key.json", foreground: "a5cdea" },
      { token: "operator", foreground: "a5cdea" },
      { token: "function", foreground: "a5cdea" },
      { token: "tag", foreground: "a5cdea" },
      { token: "metatag", foreground: "a5cdea" },
      { token: "comment", foreground: "bfc3cf", fontStyle: "italic" },
      { token: "delimiter", foreground: "bfc3cf" },
      { token: "identifier", foreground: "eceef3" },
      { token: "variable", foreground: "eceef3" },
    ],
    colors: {
      "editor.background": "#1f2025",
      "editor.foreground": "#eceef3",
      "editorGutter.background": "#1f2025",
      "editor.lineHighlightBackground": "#2b2c33",
      "editor.selectionBackground": "#2c3457",
      "editorCursor.foreground": "#abb7ff",
      "editor.inactiveSelectionBackground": "#31333b",
      "editorLineNumber.foreground": "#bfc3cf",
      "editorLineNumber.activeForeground": "#eceef3",
      "editorIndentGuide.background": "#393c46",
      "editorIndentGuide.activeBackground": "#666d7e",
      "editorWhitespace.foreground": "#666d7e",
      "editorBracketMatch.background": "#2c3457",
      "editorBracketMatch.border": "#abb7ff",
      "scrollbarSlider.background": "#4f546280",
      "scrollbarSlider.hoverBackground": "#70798d80",
      "scrollbarSlider.activeBackground": "#70798dcc",
    },
  });
  monaco.editor.defineTheme("unfour-light", {
    base: "vs",
    inherit: true,
    rules: [
      { token: "keyword", foreground: "6e4a96" },
      { token: "keyword.sql", foreground: "6e4a96" },
      { token: "keyword.json", foreground: "6e4a96" },
      { token: "attribute.name", foreground: "6e4a96" },
      { token: "string", foreground: "206747" },
      { token: "string.sql", foreground: "206747" },
      { token: "string.value.json", foreground: "206747" },
      { token: "attribute.value", foreground: "206747" },
      { token: "number", foreground: "755008" },
      { token: "number.json", foreground: "755008" },
      { token: "type", foreground: "755008" },
      { token: "string.key.json", foreground: "275e87" },
      { token: "operator", foreground: "275e87" },
      { token: "function", foreground: "275e87" },
      { token: "tag", foreground: "275e87" },
      { token: "metatag", foreground: "275e87" },
      { token: "comment", foreground: "50545d", fontStyle: "italic" },
      { token: "delimiter", foreground: "50545d" },
      { token: "identifier", foreground: "24262b" },
      { token: "variable", foreground: "24262b" },
    ],
    colors: {
      "editor.background": "#ffffff",
      "editor.foreground": "#24262b",
      "editorGutter.background": "#ffffff",
      "editor.lineHighlightBackground": "#f2f2f3",
      "editor.selectionBackground": "#eee7fa",
      "editorCursor.foreground": "#7640cd",
      "editor.inactiveSelectionBackground": "#e9eaec",
      "editorLineNumber.foreground": "#50545d",
      "editorLineNumber.activeForeground": "#24262b",
      "editorIndentGuide.background": "#d7d9dd",
      "editorIndentGuide.activeBackground": "#a9adb5",
      "editorWhitespace.foreground": "#a9adb5",
      "editorBracketMatch.background": "#eee7fa",
      "editorBracketMatch.border": "#7640cd",
      "scrollbarSlider.background": "#b6bac280",
      "scrollbarSlider.hoverBackground": "#969da980",
      "scrollbarSlider.activeBackground": "#969da9cc",
    },
  });
  monaco.editor.setTheme(`unfour-${theme}`);
}
